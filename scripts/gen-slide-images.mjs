// Generate src/data/slideImages.ts from scripts/slide-manifest.json
// (produced by the curation pass). Run after the manifest changes:
//   node scripts/gen-slide-images.mjs
import { readFileSync, writeFileSync } from 'fs';

const manifest = JSON.parse(readFileSync('scripts/slide-manifest.json', 'utf8'));

const importLines = [];
const entries = [];
let counter = 0;

for (const [islandId, paragraphs] of Object.entries(manifest)) {
  const paraEntries = [];
  for (const [paraIdx, info] of Object.entries(paragraphs)) {
    const varName = `img${++counter}_${islandId.replace(/\W/g, '')}_${paraIdx}`;
    importLines.push(`import ${varName} from "@/assets/history/slides/${info.file}";`);
    const credit = info.credit ? `, credit: ${JSON.stringify(info.credit)}` : '';
    paraEntries.push(`    ${paraIdx}: { src: ${varName}, alt: ${JSON.stringify(info.alt)}${credit} },`);
  }
  entries.push(`  "${islandId}": {\n${paraEntries.join('\n')}\n  },`);
}

const out = `// GENERATED by scripts/gen-slide-images.mjs from scripts/slide-manifest.json.
// Public-domain artwork from Wikimedia Commons, matched to quest reading
// paragraphs. Edit the manifest and regenerate rather than editing this file.
import type { SlideImage } from "@/components/history/PaginatedReading";

${importLines.join('\n')}

export const SLIDE_IMAGES: Record<string, Record<number, SlideImage>> = {
${entries.join('\n')}
};
`;

writeFileSync('src/data/slideImages.ts', out, 'utf8');
console.log(`Wrote src/data/slideImages.ts: ${Object.keys(manifest).length} islands, ${counter} images.`);
